// Command prismagen generates Go structs from the Prisma schema so the Go backend
// shares one model source of truth with the Node backend.
//
// Usage: go run ./tools/prismagen -schema ../server/prisma/schema.prisma -out src/models/models_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"
	"unicode"
)

type field struct {
	Name       string
	Base       string
	Optional   bool
	List       bool
	Column     string
	IsID       bool
	AutoInc    bool
	UpdatedAt  bool
	IsRelation bool
}

type model struct {
	Name        string
	Table       string
	Fields      []field
	CompositeID []string
}

type enum struct {
	Name   string
	Values []string
}

var (
	blockRe   = regexp.MustCompile(`(?ms)^(model|enum)\s+(\w+)\s*\{(.*?)^\}`)
	lineRe    = regexp.MustCompile(`(?m)^\s*(\w+)\s+([\w\[\]\?]+)\s*(.*)$`)
	mapRe     = regexp.MustCompile(`@map\("([^"]+)"\)`)
	tableMap  = regexp.MustCompile(`@@map\("([^"]+)"\)`)
	composite = regexp.MustCompile(`@@id\(\[([^\]]+)\]\)`)
	commentRe = regexp.MustCompile(`(?m)//.*$`)
)

func main() {
	schemaPath := flag.String("schema", "../server/prisma/schema.prisma", "path to schema.prisma")
	outPath := flag.String("out", "src/models/models_gen.go", "output Go file")
	flag.Parse()

	raw, err := os.ReadFile(*schemaPath)
	if err != nil {
		fatal("read schema: %v", err)
	}
	content := commentRe.ReplaceAllString(string(raw), "")

	enumNames := map[string]bool{}
	modelNames := map[string]bool{}
	var models []model
	var enums []enum

	for _, m := range blockRe.FindAllStringSubmatch(content, -1) {
		kind, name, body := m[1], m[2], m[3]
		if kind == "enum" {
			enumNames[name] = true
			var values []string
			for _, line := range strings.Split(body, "\n") {
				line = strings.TrimSpace(line)
				if line == "" || strings.HasPrefix(line, "@@") || strings.HasPrefix(line, "///") {
					continue
				}
				values = append(values, strings.Fields(line)[0])
			}
			enums = append(enums, enum{Name: name, Values: values})
			continue
		}

		modelNames[name] = true
		mdl := model{Name: name, Table: lowerFirst(name)}
		if tm := tableMap.FindStringSubmatch(body); tm != nil {
			mdl.Table = tm[1]
		}
		if cm := composite.FindStringSubmatch(body); cm != nil {
			for _, part := range strings.Split(cm[1], ",") {
				mdl.CompositeID = append(mdl.CompositeID, strings.TrimSpace(part))
			}
		}
		for _, line := range strings.Split(body, "\n") {
			trimmed := strings.TrimSpace(line)
			if trimmed == "" || strings.HasPrefix(trimmed, "@@") || strings.HasPrefix(trimmed, "///") {
				continue
			}
			lm := lineRe.FindStringSubmatch(trimmed)
			if lm == nil {
				continue
			}
			f := field{Name: lm[1], Column: lm[1]}
			rawType, attrs := lm[2], lm[3]
			f.Optional = strings.HasSuffix(rawType, "?")
			f.List = strings.Contains(rawType, "[]")
			f.Base = strings.NewReplacer("?", "", "[]", "").Replace(rawType)
			if mm := mapRe.FindStringSubmatch(attrs); mm != nil {
				f.Column = mm[1]
			}
			f.IsID = strings.Contains(attrs, "@id")
			f.AutoInc = strings.Contains(attrs, "@default(autoincrement())")
			f.UpdatedAt = strings.Contains(attrs, "@updatedAt")
			mdl.Fields = append(mdl.Fields, f)
		}
		models = append(models, mdl)
	}

	// Second pass: mark relations now that all model names are known.
	for i := range models {
		for j := range models[i].Fields {
			f := &models[i].Fields[j]
			if modelNames[f.Base] && !enumNames[f.Base] {
				f.IsRelation = true
			}
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/prismagen from server/prisma/schema.prisma. DO NOT EDIT.\n\n")
	buf.WriteString("package models\n\n")
	buf.WriteString("import (\n\t\"time\"\n\n\t\"gorm.io/datatypes\"\n)\n\n")
	buf.WriteString(fmt.Sprintf("// Models generated from schema.prisma: %d models, %d enums.\n\n", len(models), len(enums)))

	buf.WriteString("// ModelNames lists every generated model (used by parity tests).\nvar ModelNames = []string{\n")
	for _, m := range models {
		buf.WriteString(fmt.Sprintf("\t%q,\n", m.Name))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("// EnumNames lists every generated enum (used by parity tests).\nvar EnumNames = []string{\n")
	for _, e := range enums {
		buf.WriteString(fmt.Sprintf("\t%q,\n", e.Name))
	}
	buf.WriteString("}\n\n")

	for _, e := range enums {
		buf.WriteString(fmt.Sprintf("// %s mirrors the Prisma enum %s.\n", e.Name, e.Name))
		buf.WriteString(fmt.Sprintf("type %s string\n\nconst (\n", e.Name))
		for _, v := range e.Values {
			buf.WriteString(fmt.Sprintf("\t%s%s %s = %q\n", e.Name, pascal(v), e.Name, v))
		}
		buf.WriteString(")\n\n")
	}

	for _, m := range models {
		compositeSet := map[string]bool{}
		for _, c := range m.CompositeID {
			compositeSet[c] = true
		}
		buf.WriteString(fmt.Sprintf("// %s mirrors the Prisma model %s (table %q).\n", m.Name, m.Name, m.Table))
		buf.WriteString(fmt.Sprintf("type %s struct {\n", m.Name))
		for _, f := range m.Fields {
			buf.WriteString(generateField(f, compositeSet[f.Name]))
		}
		buf.WriteString("}\n\n")
		buf.WriteString(fmt.Sprintf("// TableName pins the GORM table for %s.\n", m.Name))
		buf.WriteString(fmt.Sprintf("func (%s) TableName() string { return %q }\n\n", m.Name, m.Table))
	}

	if err := os.WriteFile(*outPath, buf.Bytes(), 0o644); err != nil {
		fatal("write output: %v", err)
	}
	fmt.Printf("prismagen: wrote %s (%d models, %d enums)\n", *outPath, len(models), len(enums))
}

func generateField(f field, composite bool) string {
	goName := goFieldName(f.Name)
	var goType string

	switch {
	case f.IsRelation:
		base := "*" + f.Base
		if f.List {
			base = "[]" + f.Base
		}
		goType = base
	case isScalar(f.Base):
		goType = scalarGoType(f.Base, f.List)
		if f.Optional && !f.List && !isPointerLike(f.Base) {
			goType = "*" + goType
		}
	default:
		// Enum type.
		goType = f.Base
		if f.List {
			goType = "[]" + f.Base
		} else if f.Optional {
			goType = "*" + f.Base
		}
	}

	tags := buildTags(f, composite)
	return fmt.Sprintf("\t%s %s `%s`\n", goName, goType, tags)
}

func buildTags(f field, composite bool) string {
	var gormParts []string
	if f.IsRelation {
		gormParts = append(gormParts, "-")
	} else {
		gormParts = append(gormParts, "column:"+f.Column)
		if f.IsID || composite {
			gormParts = append(gormParts, "primaryKey")
		}
		if f.AutoInc {
			gormParts = append(gormParts, "autoIncrement")
		}
		if f.UpdatedAt {
			gormParts = append(gormParts, "autoUpdateTime")
		}
	}

	jsonName := f.Name
	jsonOpt := ""
	if f.IsRelation {
		jsonOpt = ",omitempty"
	}
	return fmt.Sprintf(`gorm:"%s" json:"%s%s"`, strings.Join(gormParts, ";"), jsonName, jsonOpt)
}

func isScalar(base string) bool {
	switch base {
	case "String", "Int", "BigInt", "Float", "Decimal", "Boolean", "DateTime", "Json", "Bytes":
		return true
	}
	return false
}

func isPointerLike(base string) bool {
	return base == "Json" || base == "Bytes"
}

func scalarGoType(base string, list bool) string {
	if list {
		if base == "Int" {
			return "[]int32"
		}
		return "[]" + scalarBase(base)
	}
	return scalarBase(base)
}

func scalarBase(base string) string {
	switch base {
	case "String":
		return "string"
	case "Int":
		return "int32"
	case "BigInt":
		return "int64"
	case "Float":
		return "float64"
	case "Decimal":
		return "Decimal"
	case "Boolean":
		return "bool"
	case "DateTime":
		return "time.Time"
	case "Json":
		return "datatypes.JSON"
	case "Bytes":
		return "[]byte"
	}
	return "any"
}

var initialisms = map[string]string{
	"id": "ID", "ip": "IP", "ipv4": "IPv4", "ipv6": "IPv6", "url": "URL", "uri": "URI",
	"api": "API", "http": "HTTP", "https": "HTTPS", "json": "JSON", "sql": "SQL",
	"ssh": "SSH", "smtp": "SMTP", "cpu": "CPU", "gpu": "GPU", "ram": "RAM", "os": "OS",
	"tls": "TLS", "uuid": "UUID", "oauth": "OAuth", "totp": "TOTP", "nat": "NAT",
	"vm": "VM", "kvm": "KVM", "mac": "MAC", "dns": "DNS", "ttl": "TTL", "ui": "UI",
	"db": "DB", "jwt": "JWT", "pat": "PAT", "poa": "POA", "cdn": "CDN", "acl": "ACL",
	"s3": "S3", "iso": "ISO", "tz": "TZ", "io": "IO", "gb": "GB", "mb": "MB",
	"kb": "KB", "tb": "TB", "cidr": "CIDR", "spice": "SPICE", "geo": "Geo",
}

func goFieldName(name string) string {
	words := splitCamel(name)
	for i, w := range words {
		if mapped, ok := initialisms[strings.ToLower(w)]; ok {
			words[i] = mapped
		} else {
			words[i] = capitalize(w)
		}
	}
	return strings.Join(words, "")
}

func splitCamel(s string) []string {
	var words []string
	var current []rune
	for i, r := range s {
		if i > 0 && unicode.IsUpper(r) {
			// Break before an uppercase run only if the previous rune is lower/digit,
			// or the next rune is lower (end of an acronym).
			prev := rune(s[i-1])
			nextLower := i+1 < len(s) && unicode.IsLower(rune(s[i+1]))
			if unicode.IsLower(prev) || unicode.IsDigit(prev) || nextLower {
				words = append(words, string(current))
				current = nil
			}
		}
		current = append(current, r)
	}
	if len(current) > 0 {
		words = append(words, string(current))
	}
	return words
}

func pascal(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		parts[i] = capitalize(p)
	}
	return strings.Join(parts, "")
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "prismagen: "+format+"\n", args...)
	os.Exit(1)
}
